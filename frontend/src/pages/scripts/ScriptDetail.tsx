import { useId, useState } from 'react';
import { api } from '../../api/client';
import { formatAgo, formatDateTime } from '../../format';
import { useConfirm } from '../../hooks/useConfirm';
import { IconBookmark, IconCheck, IconChevronLeft, IconCopy, IconMore, IconPlay } from '../../icons';
import { osMatchesDevice } from '../../scriptOs';
import type { Device, Job, Script } from '../../types';
import { Menu, StatusBadge } from '../../ui';
import { notify, trackJob } from '../../ui/toast';
import { JobConsole } from '../device/JobConsole';
import { CATEGORY_LABEL, OS_LABEL } from './scriptMeta';

/** Read-only source with line numbers. The numbers are generated by CSS, so
 *  copying the text copies the script and nothing else. */
export function CodeView({ content }: { content: string }) {
  const lines = content.replace(/\n$/, '').split('\n');
  return (
    // eslint-disable-next-line jsx-a11y/no-noninteractive-tabindex -- long scripts scroll sideways; keyboard users need to reach the box to scroll it.
    <pre className="code-view" tabIndex={0} aria-label="Quelltext">
      <code>
        {lines.map((l, i) => (
          <span key={i} className="code-line">
            {l || ' '}
            {'\n'}
          </span>
        ))}
      </code>
    </pre>
  );
}

interface Props {
  script: Script;
  devices: Device[];
  canManage: boolean;
  favorite: boolean;
  onToggleFavorite: () => void;
  onEdit: () => void;
  onDuplicate: () => void;
  onDelete: () => void;
  onBack: () => void;
}

/**
 * One script: what it is, its source, and a place to run it. The output
 * streams right here — before, starting a script jumped to the device page,
 * away from the script someone was looking at.
 */
export function ScriptDetail({ script: s, devices, canManage, favorite, onToggleFavorite, onEdit, onDuplicate, onDelete, onBack }: Props) {
  const { ask, dialog } = useConfirm();
  const targetId = useId();
  const runnable = devices.filter((d) => d.connected && osMatchesDevice(s.os, d.os));
  const [target, setTarget] = useState<number | ''>('');
  const [active, setActive] = useState<{ job: Job; host: string } | null>(null);
  const [copied, setCopied] = useState(false);
  const chosen = runnable.find((d) => d.id === target) ?? null;

  const run = async () => {
    if (!chosen) return;
    // A destructive script asks for its own name: a stray click reaches a real
    // machine as root.
    const ok = await ask({
      title: s.danger ? `Destruktives Skript auf ${chosen.hostname}` : `${s.name} auf ${chosen.hostname} ausführen?`,
      body: s.danger ? (
        <p>
          <b>{s.name}</b> ist als destruktiv markiert und läuft auf <b>{chosen.hostname}</b> mit vollen Rechten. Es kann
          Daten zerstören oder das Gerät lahmlegen.
        </p>
      ) : (
        <p>
          Läuft auf <b>{chosen.hostname}</b> mit vollen Rechten.
        </p>
      ),
      confirmLabel: 'Jetzt ausführen',
      danger: s.danger,
      requireText: s.danger ? s.name : undefined,
    });
    if (!ok) return;
    try {
      const r = await api.createScriptJob(chosen.id, s.id);
      setActive({ job: r.job, host: chosen.hostname });
      trackJob(r.job, { deviceName: chosen.hostname, label: s.name });
    } catch (e) {
      notify.error('Skript nicht gestartet', e);
    }
  };

  const copy = () =>
    void navigator.clipboard?.writeText(s.content).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    });

  return (
    <article className="sc-detail" aria-labelledby={`${targetId}-title`}>
      {dialog}
      <button type="button" className="link-btn sc-back" onClick={onBack}>
        <IconChevronLeft size={14} /> Alle Skripte
      </button>
      <header className="sc-detail-head">
        <div className="sc-detail-title">
          <h2 id={`${targetId}-title`}>{s.name}</h2>
          <p className="sc-detail-meta">
            {s.danger && <StatusBadge kind="danger" label="destruktiv" />}
            <span>{OS_LABEL[s.os]}</span>
            <span>{CATEGORY_LABEL[s.category]}</span>
            <span className="num">{s.shell}</span>
            <span title={formatDateTime(s.updated_at)}>
              {s.updated_by ? `${s.updated_by}, ` : ''}
              {formatAgo(s.updated_at)}
            </span>
          </p>
        </div>
        <div className="sc-detail-actions">
          <button type="button" className={favorite ? 'btn btn-icon btn-accent' : 'btn btn-icon'} aria-pressed={favorite} aria-label="Favorit" title="Favorit" onClick={onToggleFavorite}>
            <IconBookmark size={15} />
          </button>
          {canManage && (
            <>
              <button type="button" className="btn" onClick={onEdit}>
                Bearbeiten
              </button>
              <Menu
                label={`Aktionen für ${s.name}`}
                items={[
                  { label: 'Duplizieren', onSelect: onDuplicate },
                  'separator',
                  { label: 'Löschen …', danger: true, onSelect: onDelete },
                ]}
                trigger={(t) => (
                  <button type="button" className="btn btn-icon" aria-label="Weitere Aktionen" {...t}>
                    <IconMore size={16} />
                  </button>
                )}
              />
            </>
          )}
        </div>
      </header>

      {canManage && (
        <section className="sc-run" aria-label="Ausführen">
          <label htmlFor={targetId} className="field-label">
            Ausführen auf
          </label>
          <div className="sc-run-row">
            <select id={targetId} className="input" value={target} onChange={(e) => setTarget(e.target.value ? Number(e.target.value) : '')} disabled={runnable.length === 0}>
              <option value="">
                {runnable.length === 0 ? (s.os === 'any' ? 'kein Gerät verbunden' : `kein ${OS_LABEL[s.os]}-Gerät verbunden`) : 'Gerät wählen …'}
              </option>
              {runnable.map((d) => (
                <option key={d.id} value={d.id}>
                  {d.hostname}
                </option>
              ))}
            </select>
            <button type="button" className={s.danger ? 'btn btn-danger' : 'btn btn-primary'} disabled={!chosen} onClick={() => void run()}>
              <IconPlay size={14} /> Ausführen
            </button>
          </div>
          <p className="field-hint">Für viele Geräte auf einmal: in der Geräteliste auswählen und „Skript ausführen".</p>
        </section>
      )}

      {active && (
        <JobConsole
          jobId={active.job.id}
          title={`${s.name} @ ${active.host}`}
          actions={
            <button type="button" className="console-btn" onClick={() => setActive(null)}>
              Schließen
            </button>
          }
        />
      )}

      <section className="sc-source" aria-label="Quelltext">
        <div className="sc-source-head">
          <span className="sc-source-title">Quelltext</span>
          <button type="button" className="btn btn-sm btn-ghost" onClick={copy}>
            {copied ? <IconCheck size={14} /> : <IconCopy size={14} />} {copied ? 'Kopiert' : 'Kopieren'}
          </button>
        </div>
        <CodeView content={s.content} />
      </section>
    </article>
  );
}
