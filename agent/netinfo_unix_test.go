package main

import (
	"bytes"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

func TestParseResolvConf(t *testing.T) {
	in := "# generated by NetworkManager\n" +
		"search fritz.box\n" +
		"nameserver 192.168.2.1\n" +
		"  nameserver\tfe80::1%eth0  # link-local\r\n" +
		"#nameserver 10.0.0.1\n" +
		"nameservers 10.0.0.2\n" +
		"nameserver\n" +
		"options edns0 trust-ad\n" +
		"nameserver 1.1.1.1"
	want := []string{"192.168.2.1", "fe80::1%eth0", "1.1.1.1"}
	if got := parseResolvConf(strings.NewReader(in)); !reflect.DeepEqual(got, want) {
		t.Fatalf("got %q, want %q", got, want)
	}
}

func TestReadResolvConf(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	if err := os.WriteFile(path, []byte("nameserver 9.9.9.9\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if got := readResolvConf(path); !reflect.DeepEqual(got, []string{"9.9.9.9"}) {
		t.Errorf("got %q", got)
	}
	if got := readResolvConf(filepath.Join(t.TempDir(), "missing")); got != nil {
		t.Errorf("missing file: got %q, want nil", got)
	}
}

// Invariants: no panic; every entry is one whitespace-free token taken from
// the input; and writing the entries back as plain nameserver lines parses
// to the same list (round trip).
func FuzzParseResolvConf(f *testing.F) {
	f.Add([]byte("nameserver 127.0.0.53\noptions edns0 trust-ad\nsearch .\n"))
	f.Add([]byte("domain lan\nnameserver 192.168.2.1\nnameserver 2001:db8::1\n"))
	f.Add([]byte("  nameserver\tfe80::1%eth0 # comment\r\n#nameserver 10.0.0.1\n"))
	f.Add([]byte("nameservers 10.0.0.2\nnameserver\nnameserver 1.1.1.1"))
	f.Add([]byte("nameserver 1.1.1.1\nnameserver \xff\xfe\n"))
	f.Add([]byte(""))
	f.Fuzz(func(t *testing.T, in []byte) {
		got := parseResolvConf(bytes.NewReader(in))
		if len(got) > bytes.Count(in, []byte("\n"))+1 {
			t.Fatalf("%d entries from %d lines", len(got), bytes.Count(in, []byte("\n"))+1)
		}
		var canon strings.Builder
		for _, e := range got {
			if tok := strings.Fields(e); len(tok) != 1 || tok[0] != e {
				t.Fatalf("entry %q is not a single token", e)
			}
			if !bytes.Contains(in, []byte(e)) {
				t.Fatalf("entry %q does not occur in the input", e)
			}
			canon.WriteString("nameserver " + e + "\n")
		}
		if again := parseResolvConf(strings.NewReader(canon.String())); !reflect.DeepEqual(again, got) {
			t.Fatalf("round trip: %q became %q", got, again)
		}
	})
}
